-- Таблица пользователей
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    role VARCHAR(50) NOT NULL,
    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'CUSTOMER', 'MANAGER'))
);

-- Таблица абонементов
CREATE TABLE memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    membership_type VARCHAR(50) NOT NULL,
    visits_left INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT fk_memberships_client
        FOREIGN KEY (client_id)
        REFERENCES users(id)
        ON DELETE CASCADE,
    CONSTRAINT chk_memberships_visits CHECK (visits_left >= 0),
    CONSTRAINT chk_memberships_dates CHECK (end_date >= start_date)
);

-- Индекс для ускорения поиска абонементов клиента
CREATE INDEX idx_memberships_client_id ON memberships(client_id);